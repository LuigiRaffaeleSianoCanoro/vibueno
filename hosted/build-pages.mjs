#!/usr/bin/env node
/**
 * Bundles HTML templates and the Worker into a single Cloudflare Pages artifact.
 */
import * as esbuild from 'esbuild';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROUTE_TEMPLATES } from './routes.mjs';

const exec = promisify(execFile);
const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..');

async function gitSha() {
  if (process.env.GITHUB_SHA) return String(process.env.GITHUB_SHA).trim().slice(0, 40);
  if (process.env.SOURCE_COMMIT) return String(process.env.SOURCE_COMMIT).trim().slice(0, 40);
  try {
    const { stdout } = await exec('git', ['rev-parse', 'HEAD'], { cwd: repoRoot });
    return stdout.trim().slice(0, 40);
  } catch {
    return 'unknown';
  }
}

async function loadTemplates() {
  const out = {};
  for (const [name, { file }] of Object.entries(ROUTE_TEMPLATES)) {
    const path = resolve(here, 'public', file);
    const text = await readFile(path, 'utf8');
    if (!text.includes('<html')) throw new Error(`Invalid or empty template: ${file}`);
    out[name] = text;
  }
  return out;
}

async function writeBundledModule(templates, sha) {
  const body = `// @generated by build:pages — do not edit by hand
export const BUILD_SHA = ${JSON.stringify(sha)};
export const BUNDLED_TEMPLATES = ${JSON.stringify(templates)};
export const REGISTERED_TEMPLATE_NAMES = ${JSON.stringify(Object.keys(templates))};
`;
  await writeFile(resolve(here, 'bundled-templates.mjs'), body, 'utf8');
}

const sha = await gitSha();
const templates = await loadTemplates();
await writeBundledModule(templates, sha);

await esbuild.build({
  entryPoints: [resolve(here, 'worker.js')],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  outfile: resolve(here, 'public/_worker.js'),
  logLevel: 'info',
});

console.log(`built public/_worker.js (sha ${sha}, templates: ${Object.keys(templates).join(', ')})`);