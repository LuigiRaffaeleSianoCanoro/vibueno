#!/usr/bin/env node
/**
 * Bundles HTML templates and the Worker into a single Cloudflare Pages artifact.
 * Optional VIBUENO_OUTPUT_ROOT: write worker + bundle to a separate dir (parallel-safe tests).
 */
import * as esbuild from 'esbuild';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { cp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROUTE_TEMPLATES } from './routes.mjs';
import { resolveBuildSha } from './build-sha.mjs';

const exec = promisify(execFile);
const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..');
const outRoot = process.env.VIBUENO_OUTPUT_ROOT ? resolve(process.env.VIBUENO_OUTPUT_ROOT) : here;

async function ensureOutRootWorker() {
  if (outRoot === here) return;
  await mkdir(resolve(outRoot, 'public'), { recursive: true });
  for (const f of ['worker.js', 'routes.mjs', 'build-sha.mjs', 'version.mjs']) {
    await cp(resolve(here, f), resolve(outRoot, f));
  }
}

async function loadTemplates() {
  /** @type {Record<string, string>} */
  const out = {};
  for (const [name, { file }] of Object.entries(ROUTE_TEMPLATES)) {
    const path = resolve(here, 'public', file);
    const text = await readFile(path, 'utf8');
    if (!text.includes('<html')) throw new Error(`Invalid or empty template: ${file}`);
    out[name] = text;
  }
  return out;
}

/**
 * @param {Record<string, string>} templates
 * @param {{ sha: string, ok: boolean, dirty: boolean }} version
 */
async function writeBundledModule(templates, version) {
  const body = `// @generated by build:pages — do not edit by hand
export const BUILD_SHA = ${JSON.stringify(version.sha)};
export const BUILD_VERSION_OK = ${JSON.stringify(version.ok)};
export const BUILD_DIRTY = ${JSON.stringify(version.dirty)};
export const BUNDLED_TEMPLATES = ${JSON.stringify(templates)};
export const REGISTERED_TEMPLATE_NAMES = ${JSON.stringify(Object.keys(templates))};
`;
  await writeFile(resolve(outRoot, 'bundled-templates.mjs'), body, 'utf8');
}

await ensureOutRootWorker();

const version = await resolveBuildSha(repoRoot, exec);
const templates = await loadTemplates();
await writeBundledModule(templates, version);

await esbuild.build({
  entryPoints: [resolve(outRoot, 'worker.js')],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  outfile: resolve(outRoot, 'public/_worker.js'),
  absWorkingDir: outRoot,
  logLevel: 'info',
});

console.log(
  `built ${resolve(outRoot, 'public/_worker.js')} (sha ${version.sha}, templates: ${Object.keys(templates).join(', ')})`,
);